export function searchTools(query: string): Tool[] {
  const q = query.trim().toLowerCase()
  if (!q) return []

  return tools
    .filter((tool) => !REDIRECTED_TOOL_IDS.has(tool.id))
    .map((tool) => {
      const inName = tool.name.toLowerCase().includes(q)
      const inDescription = tool.description.toLowerCase().includes(q)
      const inKeyword = tool.keywords.some((k) => k.toLowerCase().includes(q))
      const score =
        Number(inName) * 4 +
        Number(inKeyword) * 2 +
        Number(inDescription) +
        Number(tool.status !== "preview")
      return { tool, score }
    })
    .filter((e) => e.score > 0)
    .sort((a, b) => b.score - a.score || a.tool.name.localeCompare(b.tool.name))
    .map((e) => e.tool)
}


