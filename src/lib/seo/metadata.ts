function buildToolMetadataCatalogEntry(
  tool: Tool
): ToolMetadataCatalogEntry {
  const category = getCategoryById(tool.category)
  const keywordStrategy = getToolKeywordStrategy(tool.id) ?? {
    primary: [],
    secondary: [],
    longTail: [],
    all: [],
  }

  const primaryKeyword =
    keywordStrategy.primary[0] ?? normalizeQuery(tool.name)

  return {
    id: tool.id,
    name: tool.name,
    path: tool.path,
    description: tool.description,
    categoryId: tool.category,
    categoryName: category?.name ?? tool.category,
    pageType: tool.pageType ?? "static",
    status: tool.status ?? "live",
    // SEO FIX: keyword-first title — no leading "Free", benefit-focused differentiator
    title: truncate(
      `${replaceSeparators(tool.name)} — Free, No Signup, No Upload`,
      70
    ),
    // SEO FIX: lead with the primary keyword so it appears early in the snippet
    metaDescription: truncate(
      `Free ${primaryKeyword} — ${tool.description.replace(/\.$/, "")}. Runs entirely in your browser — no account or install needed.`,
      160
    ),
    keywordStrategy,
  }
}

