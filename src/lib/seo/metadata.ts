export function getToolKeywordStrategy(
  toolId: string
): KeywordStrategy | null {
  const tool = getToolById(toolId)
  if (!tool) {
    return null
  }

  const category = getCategoryById(tool.category)
  const normalizedName = normalizeQuery(replaceSeparators(tool.name))
  const topic = getToolTopic(tool)

  const primary = dedupe([
    normalizedName,
    `${normalizedName} online`,
    `free ${normalizedName}`,
    `${normalizedName} free`,
    `${normalizedName} online free`,
    `best ${normalizedName}`,
    ...buildToolActionKeywords(tool, topic).slice(0, 6),
  ])

  // Keep secondary/long-tail lean and genuinely distinct. The previous version
  // generated ~40 near-identical permutations of the tool name ("X for
  // students", "X for marketers", "X chrome", "X firefox", ...) which reads as
  // keyword-stuffing to a human reviewer. We now emit only meaningfully
  // different intents, plus the tool's own hand-written keywords.
  const secondary = dedupe([
    `${normalizedName} tool`,
    `${topic} tool`,
    `${normalizedName} no signup`,
    `${normalizedName} browser based`,
    ...tool.keywords.map((keyword) => normalizeQuery(keyword)),
  ])

  const longTail = dedupe([
    `free online ${normalizedName}`,
    `${normalizedName} without signup`,
    `how to ${topic} online free`,
    `best free ${normalizedName}`,
    ...buildToolActionKeywords(tool, topic).slice(6),
  ])

  return {
    primary,
    secondary,
    longTail,
    // Cap the meta keywords list low and prioritise the tool's real terms.
    all: dedupe([...primary, ...tool.keywords.map((k) => normalizeQuery(k))], 12),
  }
}

