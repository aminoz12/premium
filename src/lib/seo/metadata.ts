function normalizeQuery(value: string) {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^\w\s-]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

function dedupe(values: string[], limit = 18) {
  const seen = new Set<string>()
  const deduped: string[] = []

  for (const value of values) {
    const normalized = normalizeQuery(value)
    if (!normalized || seen.has(normalized)) {
      continue
    }

    seen.add(normalized)
    deduped.push(normalized)

    if (deduped.length >= limit) {
      break
    }
  }

  return deduped
}

function replaceSeparators(value: string) {
  return value.replace(/\//g, " & ").replace(/\s+/g, " ").trim()
}

function ensureToolsPhrase(value: string) {
  const normalized = normalizeQuery(value)
  return /\btools?\b/.test(normalized) ? normalized : `${normalized} tools`
}

function truncate(value: string, maxLength: number) {
  if (value.length <= maxLength) {
    return value
  }

  const trimmed = value.slice(0, maxLength - 1).trimEnd()
  const breakpoint = trimmed.lastIndexOf(" ")

  return `${(breakpoint > 40 ? trimmed.slice(0, breakpoint) : trimmed).trimEnd()}.`
}

function getToolTopic(tool: Tool) {
  const candidate =
    tool.keywords.find(
      (keyword) => !actionWords.has(normalizeQuery(keyword))
    ) ??
    tool.name.split(/[&/]/)[0] ??
    tool.name

  return normalizeQuery(candidate)
}

